-- 初期DB定義SQL (PostgreSQL / Supabase 向け)
-- 既存の Flask アプリのモデルに対応したテーブルを作成します。
-- そのまま Supabase の SQL Editor で実行してください。

BEGIN;

CREATE TABLE IF NOT EXISTS public."user" (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(50) NOT NULL UNIQUE,
    passkey_enrollment_token varchar(128) UNIQUE,
    passkey_enrollment_expires_at timestamp without time zone
);

CREATE TABLE IF NOT EXISTS public.credential (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES public."user"(id),
    credential_id bytea NOT NULL UNIQUE,
    public_key bytea NOT NULL,
    sign_count integer DEFAULT 0
);

CREATE TABLE IF NOT EXISTS public.title (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(50) NOT NULL UNIQUE,
    badge_filename text NOT NULL,
    required_total_games integer DEFAULT 0,
    required_avg_rank double precision DEFAULT 4.1,
    required_win_count integer DEFAULT 0,
    required_last_avoidance_rate double precision DEFAULT 0,
    required_highest_rank_1_rate boolean DEFAULT false,
    required_highest_last_avoidance_rate boolean DEFAULT false,
    required_highest_raw_score_std_dev boolean DEFAULT false,
    required_max_consecutive_top1 integer DEFAULT 0,
    required_max_consecutive_last integer DEFAULT 0,
    required_total_raw_score integer NOT NULL DEFAULT 0,
    required_max_raw_score integer NOT NULL DEFAULT 0,
    required_min_raw_score integer NOT NULL DEFAULT 0,
    is_permanent boolean DEFAULT false
);

CREATE TABLE IF NOT EXISTS public.player (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(50) NOT NULL,
    total_score integer DEFAULT 0,
    active_title_1_id integer,
    active_title_2_id integer,
    active_title_3_id integer,
    CONSTRAINT player_active_title_1_id_fkey FOREIGN KEY (active_title_1_id) REFERENCES public.title(id),
    CONSTRAINT player_active_title_2_id_fkey FOREIGN KEY (active_title_2_id) REFERENCES public.title(id),
    CONSTRAINT player_active_title_3_id_fkey FOREIGN KEY (active_title_3_id) REFERENCES public.title(id)
);

CREATE TABLE IF NOT EXISTS public.game (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date date DEFAULT CURRENT_DATE,
    player1_id integer REFERENCES public.player(id),
    player2_id integer REFERENCES public.player(id),
    player3_id integer REFERENCES public.player(id),
    player4_id integer REFERENCES public.player(id),
    score1 integer,
    score2 integer,
    score3 integer,
    score4 integer,
    oka integer DEFAULT 0,
    uma1 integer DEFAULT 0,
    uma2 integer DEFAULT 0,
    uma3 integer DEFAULT 0,
    uma4 integer DEFAULT 0
);

CREATE TABLE IF NOT EXISTS public.game_photo (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id integer NOT NULL UNIQUE REFERENCES public.game(id) ON DELETE CASCADE,
    image_url text,
    public_id varchar(255),
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.player_title_achievement (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id integer NOT NULL REFERENCES public.player(id),
    title_id integer NOT NULL REFERENCES public.title(id),
    unlocked_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_player_title_achievement UNIQUE (player_id, title_id)
);

-- ログインユーザーとプレイヤーの紐付け（既存DBにも追加できるよう ALTER で定義）
ALTER TABLE public."user" ADD COLUMN IF NOT EXISTS player_id integer REFERENCES public.player(id);

-- 管理者から付与される「戦績の修正・削除」権限
ALTER TABLE public."user" ADD COLUMN IF NOT EXISTS can_edit_games boolean DEFAULT false;

-- Passkey の登録日時・最終使用日時（既存の Passkey は NULL）
ALTER TABLE public.credential ADD COLUMN IF NOT EXISTS created_at timestamp without time zone;
ALTER TABLE public.credential ADD COLUMN IF NOT EXISTS last_used_at timestamp without time zone;

-- 対局ルール（オカ・ウマ）などの共通設定
CREATE TABLE IF NOT EXISTS public.app_setting (
    key varchar(50) PRIMARY KEY,
    value text NOT NULL
);

COMMIT;
